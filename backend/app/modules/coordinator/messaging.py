"""Driver messages sent as a result of a coordinator decision. Times, dates and dock codes are inserted by code into
reviewed templates (never generated by an AI model). The outbox row is written in the decision's transaction; the
WhatsApp worker (M8) renders and sends it in the driver's language."""
from uuid import UUID
from zoneinfo import ZoneInfo

from sqlalchemy.ext.asyncio import AsyncSession

from app.core.outbox import emit

TEMPLATES = ("shipment_assigned", "appointment_confirmed", "appointment_changed", "request_awaiting_approval",
             "escalation_notice", "reminder_before_slot", "arrival_update_request")


async def to_driver(db: AsyncSession, shipment_id: UUID, template: str, variables: dict) -> None:
    from app.modules.drivers import service as drivers_service
    from app.modules.shipments import service as shipments_service

    assert template in TEMPLATES, template
    s = (await shipments_service.get_many(db, [shipment_id])).get(shipment_id)
    if s is None or s.driver_id is None:
        return
    drv = (await drivers_service.get_many(db, [s.driver_id])).get(s.driver_id)
    if drv is None:
        return
    emit(db, "whatsapp.template", {
        "shipment_id": s.id, "driver_id": drv.id, "to": drv.whatsapp_number, "language": drv.preferred_language,
        "deliverable": bool(drv.whatsapp_number and drv.verified_at and drv.whatsapp_opt_in),
        "template": template, "variables": variables})


def when(dt, tz: str) -> str:
    return dt.astimezone(ZoneInfo(tz)).strftime("%d %b %H:%M")


async def slot_vars(db: AsyncSession, slot_id: UUID) -> dict:
    """Slot, dock and local times for template variables, inserted by code (never by a model)."""
    from app.modules.booking import readers

    slot = (await readers.slots_by_ids(db, [slot_id]))[slot_id]
    dock = (await readers.docks_by_ids(db, [slot.dock_id]))[slot.dock_id]
    fac = (await readers.facilities_by_ids(db, [slot.facility_id]))[slot.facility_id]
    return {"slot_code": slot.code, "dock_code": dock.dock_code, "facility": fac.facility_name,
            "start": when(slot.slot_start_ts, fac.timezone), "end": when(slot.slot_end_ts, fac.timezone)}
