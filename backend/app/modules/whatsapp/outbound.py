"""Shared contract between the WhatsApp channel (modules/whatsapp) and the driver agent (modules/agent).

The agent returns OutboundMessage objects; the channel persists and sends them (Cloud API, or the simulator sink).
Times, dates and dock codes inside `text` are always inserted by code into reviewed strings, never generated by a model."""
from dataclasses import dataclass, field
from uuid import UUID

MAX_BUTTONS = 3
MAX_ROWS = 10
BUTTON_TITLE_MAX = 20
ROW_TITLE_MAX = 24
ROW_DESC_MAX = 72


@dataclass
class Button:
    id: str
    title: str


@dataclass
class Row:
    id: str
    title: str
    description: str = ""


@dataclass
class OutboundMessage:
    kind: str  # "text" | "buttons" | "list"
    text: str
    buttons: list[Button] = field(default_factory=list)
    list_button: str | None = None
    rows: list[Row] = field(default_factory=list)
    language: str = "en"
    purpose: str = ""

    def validate(self) -> "OutboundMessage":
        if self.kind == "buttons":
            assert 1 <= len(self.buttons) <= MAX_BUTTONS, "WhatsApp allows 1-3 reply buttons"
            for b in self.buttons:
                b.title = b.title[:BUTTON_TITLE_MAX]
        if self.kind == "list":
            assert 1 <= len(self.rows) <= MAX_ROWS, "WhatsApp lists allow up to 10 rows"
            for r in self.rows:
                r.title, r.description = r.title[:ROW_TITLE_MAX], r.description[:ROW_DESC_MAX]
        return self


@dataclass
class AgentReply:
    messages: list[OutboundMessage] = field(default_factory=list)
    escalated: bool = False
    language: str = "en"
    intent: str | None = None
    requires_human_review: bool = False
    escalation_id: UUID | None = None
    stage: str | None = None
