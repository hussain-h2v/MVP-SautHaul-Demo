def buttons_for(name: str, language: str) -> list[dict]:
    if name != "appointment_changed":
        return []
    accept, decline = OFFER_BUTTONS.get(language, OFFER_BUTTONS["en"])
    return [{"id": "offer_accept", "title": accept, "when": "offer"}, {"id": "offer_decline", "title": decline, "when": "offer"}]


def seed_rows() -> list[dict]:
    rows = []
    for name, (category, variables, bodies) in TEMPLATES.items():
        for lang, body in bodies.items():
            rows.append({"name": name, "language": lang, "category": category, "body": body, "variables": variables,
                         "buttons": buttons_for(name, lang), "approval_status": "approved", "needs_native_review": lang != "en"})
    return rows
